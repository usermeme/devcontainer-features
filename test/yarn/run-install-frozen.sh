#!/usr/bin/env bash
set -e

source dev-container-features-test-lib

as_node() {
  if [ "$(id -u)" = "0" ]; then
    su node -s /bin/bash -c "$1"
  else
    bash -c "$1"
  fi
}

# Regression: runInstall/immutable were never read at postCreate, and an out-of-date
# lockfile was silently rewritten by a fallback `yarn install`.
check "runInstall=true persisted" grep -qx 'RUNINSTALL=true' /usr/local/share/yarn/options.env

PROJECT="$(mktemp -d)"
chmod 755 "$PROJECT"
cat >"$PROJECT/package.json" <<'JSON'
{ "name": "probe", "version": "1.0.0", "dependencies": { "left-pad": "1.3.0" } }
JSON
printf '# THIS IS AN AUTOGENERATED FILE.\n# yarn lockfile v1\n\n' >"$PROJECT/yarn.lock"
chown -R node "$PROJECT" 2>/dev/null || true

check "out-of-date lockfile fails the install" as_node "cd '$PROJECT' && ! /usr/local/share/yarn/setup-yarn.sh"
check "lockfile was not rewritten" test "$(grep -c left-pad "$PROJECT/yarn.lock")" = 0

reportResults
